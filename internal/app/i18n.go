// T looks a key up in the configured language, then English, then returns the key.
func (a *App) T(key string) string {
	if v, ok := catalog[a.cfg.Lang][key]; ok {
		return v
	}
	if v, ok := catalog["en"][key]; ok {
		return v
	}
	return key
}
